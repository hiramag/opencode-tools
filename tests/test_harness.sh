#!/usr/bin/env bash
# Tests for the test runner itself.
#
# Origin: the EXIT trap in lib.sh swallowed the exit status, so a suite that died
# partway through was reported as PASS. A harness that always says PASS is worse
# than no harness, so this suite checks that run.sh can actually fail.

. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

section "a suite that crashes must not report PASS"

# Reproduce the original bug: a script that dies mid-way with a non-zero-ish
# error still ran its EXIT trap and ended up exiting 0.
BAD=$(mktemp -d); STORES+=("$BAD")
cat > "$BAD/crash.sh" <<'EOF'
#!/usr/bin/env bash
set -uo pipefail
cleanup() { true; }          # an EXIT trap that succeeds
trap 'rc=$?; cleanup; exit $rc' EXIT   # the fix
printf '    ok   before the crash\n'
echo "some undefined variable" >&2
echo "  $SOME_UNDEFINED_VARIABLE"  # aborts under set -u
printf '    ok   after the crash\n' # must never run
EOF
chmod +x "$BAD/crash.sh"

# Without the status-preserving trap this exits 0. With it, non-zero.
out=$("$BAD/crash.sh" 2>/dev/null); rc=$?
assert_rc "the fixed trap keeps a crash non-zero" 1 test "$rc" -eq 0

section "run.sh reports a failing suite as FAIL"

# A suite that exits non-zero must be surfaced, not swallowed.
REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
mkdir -p "$REPO/tests"
cat > "$REPO/tests/test_zzz_deliberate_failure.sh" <<SUITE
#!/usr/bin/env bash
# Generated by test_harness.sh — deliberately fails, then deletes itself.
. "$REPO/tests/lib.sh"
section "deliberate failure"
assert_eq "this case fails on purpose" "expected" "actual"
summary
SUITE

out=$(cd "$REPO/tests" && TOOL="$REPO/opencode-bash-tool.sh" bash run.sh zzz_deliberate_failure 2>&1)
rc=$?

assert_rc "run.sh exits non-zero"        1 test "$rc" -eq 0
assert_contains "run.sh says FAIL"       "FAIL" "$out"
assert_contains "it names the suite"     "zzz_deliberate_failure" "$out"
assert_contains "it shows the failure"   "this case fails on purpose" "$out"
assert_not_contains "it does NOT say PASS" "all suites passed" "$out"

rm -f "$REPO/tests/test_zzz_deliberate_failure.sh"

section "run.sh passes a good suite"

out=$(cd "$REPO/tests" && TOOL="$REPO/opencode-bash-tool.sh" bash run.sh pure 2>&1)
assert_contains "a green suite reports PASS" "test_pure" "$out"
assert_contains "and says all suites passed" "all suites passed" "$out"

section "the runner refuses to run without a tool"

# NB: never invoke run.sh with no arguments from in here. It globs every
# test_*.sh including this file, which calls run.sh again — unbounded recursion.
out=$(cd "$REPO/tests" && TOOL=/nonexistent/opencode-bash-tool.sh bash run.sh pure 2>&1); rc=$?
assert_rc "a missing tool is an error, not a pass" 1 test "$rc" -eq 0
assert_contains "  and it says which file" "cannot find the tool" "$out"

section "a named suite that does not exist"

out=$(cd "$REPO/tests" && TOOL="$REPO/opencode-bash-tool.sh" bash run.sh nosuchsuite 2>&1); rc=$?
assert_rc "  non-zero"            1 test "$rc" -eq 0
assert_contains "  and it names it" "no such suite" "$out"

summary